// Integration checks against the actual Electron renderer, using an isolated profile.
const { app, BrowserWindow } = require('electron');
const path = require('node:path');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const root = path.join(__dirname, '..');
const output = path.join(root, 'artifacts');
const profile = path.join(output, 'test-profile');
fs.mkdirSync(profile, { recursive: true });
const source = path.join(app.getPath('appData'), 'biblia-flutuante', 'biblia-ACF.json');
if (fs.existsSync(source)) fs.copyFileSync(source, path.join(profile, 'biblia-ACF.json'));
app.setPath('userData', profile);
require('../main');
const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
app.whenReady().then(async () => {
  const win = BrowserWindow.getAllWindows()[0];
  const run = script => win.webContents.executeJavaScript(script, true);
  const results = [];
  const sizes = [];
  const check = (label, value) => { assert.ok(value, label); results.push(label); };
  const capture = async name => {
    win.show(); win.restore();
    await sleep(1700);
    const bounds = win.getContentBounds();
    sizes.push({ name, bounds, viewport: await run('({width:innerWidth,height:innerHeight})') });
    const png = (await win.webContents.capturePage(undefined, { stayAwake: true })).toPNG();
    check(name + ' renderizou', png.length > 10000);
    fs.writeFileSync(path.join(output, name + '.png'), png);
  };
  try {
    if (win.webContents.isLoading()) await new Promise(resolve => win.webContents.once('did-finish-load', resolve));
    await sleep(300);
    await run('bibleReady');
    check('Texto bíblico carregado', await run('!!bible && pages.length > 0'));
    await run("(async () => { if (compact) await toggleCompact(); S.theme='dark'; S.fs=18; show(null); await openAt(true); })()");
    await capture('livro-noturno');
    await run('toggleCompact()');
    check('Janela compacta reduz a largura real', win.getBounds().width < 450);
    check('Modo compacto preserva a fonte', await run("compact && S.fs === 18 && getComputedStyle($('pR')).display === 'none'"));
    await capture('leitura-compacta');
    check('Texto cabe na página compacta', await run("document.querySelector('#pL .pbody').scrollHeight <= document.querySelector('#pL .pbody').clientHeight + 1"));
    await run("openSearch(); $('searchInput').value='João 3:16'; renderSearch()");
    check('Referência encontrada no renderer', await run("$('searchResults').querySelector('[data-ref]').dataset.ref === '42.2.15'"));
    await capture('busca-referencia');
    await run("$('searchResults').querySelector('[data-ref]').click()");
    await sleep(300);
    check('Resultado abre o versículo solicitado', await run("S.book===42 && S.chapter===2 && !!$('pL').querySelector('[data-i=\"15\"]')"));
    await run('flip(1)');
    await run('flip(-1)');
    check('Navegação compacta conserva o capítulo', await run('S.book===42 && S.chapter===2'));
    await run("openSearch(); $('searchInput').value='amor'; renderSearch()");
    check('Busca por palavra retorna resultados', await run("$('searchResults').querySelectorAll('[data-ref]').length > 1"));
    await capture('busca-palavra');
    await run("closePanels(); $('bSettings').click()");
    await capture('ajustes-backup');
    await run("closePanels(); show(null); openStudy(42,2,15)");
    await run("$('stNote').value='Última edição de teste, salva imediatamente.'; $('stNote').dispatchEvent(new Event('input',{bubbles:true}))");
    check('Nota salva imediatamente no disco pelo fluxo da interface', JSON.parse(fs.readFileSync(path.join(profile, 'meus-dados.json'), 'utf8')).data.notas['42.2.15'] === 'Última edição de teste, salva imediatamente.');
    await run("$('stTopics').value='Fé, Família'; $('stTopics').dispatchEvent(new Event('input',{bubbles:true}))");
    check('Temas salvos imediatamente pela folha de estudo', JSON.parse(fs.readFileSync(path.join(profile, 'meus-dados.json'), 'utf8')).data.temas['42.2.15'].join(', ') === 'Fé, Família');
    await capture('anotacao-compacta');
    await run("notes['0.0.0']='Uma reflexão sobre criação'; notes['18.22.0']='Oração de confiança'; topics['18.22.0']=['Oração']; hl={'42:2':{15:'y'},'0:0':{0:'g'}}; persistAll(); show('ann')");
    await run('drawAnn()');
    check('Anotações existentes sem tema continuam visíveis', await run("$('annList').querySelectorAll('[data-k]').length===3"));
    await run("$('annTopicFilter').value='topic:fe'; $('annTopicFilter').dispatchEvent(new Event('change',{bubbles:true})); $('annColorFilter').value='y'; $('annColorFilter').dispatchEvent(new Event('change',{bubbles:true})); $('annQuery').value='FAMILIA'; $('annQuery').dispatchEvent(new Event('input',{bubbles:true}))");
    check('Filtros combinados preservam a seleção correta', await run("$('annList').querySelectorAll('[data-k]').length===1 && annSel==='42.2.15' && $('annTopics').value==='Fé, Família'"));
    await capture('anotacoes-temas-compacto');
    check('Filtros e editor cabem no modo compacto', await run("$('annL').scrollHeight <= $('annL').clientHeight+1 && $('annR').scrollHeight <= $('annR').clientHeight+1"));
    await run("$('annTopics').value='Família'; $('annTopics').dispatchEvent(new Event('input',{bubbles:true}))");
    check('Remover tema mantém a nota e a edição atual mesmo fora do filtro', await run("$('annList').querySelectorAll('[data-k]').length===0 && $('annNote').value===notes['42.2.15'] && annSel==='42.2.15'"));
    check('Tema alterado persiste imediatamente', JSON.parse(fs.readFileSync(path.join(profile, 'meus-dados.json'), 'utf8')).data.temas['42.2.15'].join() === 'Família');
    await run("$('annReset').click(); $('annTopicFilter').value='none'; $('annTopicFilter').dispatchEvent(new Event('change',{bubbles:true}))");
    check('Filtro Sem tema encontra anotações antigas', await run("$('annList').querySelectorAll('[data-k]').length===1 && annSel==='0.0.0'"));
    await run("$('annReset').click(); $('annQuery').value='joao 3:16'; $('annQuery').dispatchEvent(new Event('input',{bubbles:true}))");
    check('Busca nas anotações aceita referência sem acento', await run("$('annList').querySelectorAll('[data-k]').length===1 && annSel==='42.2.15'"));
    await run("$('annQuery').value='nenhum resultado esperado'; $('annQuery').dispatchEvent(new Event('input',{bubbles:true}))");
    check('Estado vazio oferece recuperação dos filtros', await run("!$('annReset').hidden && !$('annNote') && $('annList').textContent.includes('Nenhuma anotação')"));
    await run("$('annReset').click()");
    check('Limpar filtros restaura todas as anotações', await run("$('annList').querySelectorAll('[data-k]').length===3"));
    await run("(async()=>{ await toggleCompact(); S.theme='light'; applyLook(); })()");
    await capture('anotacoes-temas-livro');
    await run("(async()=>{ S.theme='dark'; applyLook(); await toggleCompact(); })()");
    await run("show('nb'); document.querySelector('#nb [data-act=new]').click(); $('nbTitle').value='Estudo de exemplo'; $('nbTitle').dispatchEvent(new Event('input',{bubbles:true})); $('nbText').value='Reflexão de teste sobre a leitura.'; $('nbText').dispatchEvent(new Event('input',{bubbles:true}));");
    check('Estudo salvo imediatamente no disco', JSON.parse(fs.readFileSync(path.join(profile, 'meus-dados.json'), 'utf8')).data.estudos[0].text === 'Reflexão de teste sobre a leitura.');
    await capture('caderno-noturno');
    await run("show('vows'); $('vwText').value='Exemplo de votos para verificar o salvamento.'; $('vwText').dispatchEvent(new Event('input',{bubbles:true}))");
    check('Votos salvos imediatamente no disco', JSON.parse(fs.readFileSync(path.join(profile, 'meus-dados.json'), 'utf8')).data.votos.text === 'Exemplo de votos para verificar o salvamento.');
    await capture('votos-noturno');
    await run("(async () => { show(null); await openAt(true); $('bBooks').click(); })()");
    await capture('indice-compacto');
    fs.writeFileSync(path.join(output, 'verificacao.json'), JSON.stringify({ ok: true, checks: results, sizes }, null, 2));
  } catch (err) {
    fs.writeFileSync(path.join(output, 'verificacao.json'), JSON.stringify({ ok: false, checks: results, sizes, error: err.stack }, null, 2));
    process.exitCode = 1;
  } finally { app.quit(); }
});
